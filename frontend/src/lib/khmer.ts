/**
 * Look up a Khmer string. Supports i18next's `{{name}}` placeholders and its
 * `_other` plural suffix, which is how the source strings were written.
 * Unknown keys return the key itself, so a miss is visible rather than blank.
 */
export function t(key: string, params?: Record<string, unknown>): string {
  const raw = STRINGS[key] ?? STRINGS[`${key}_other`];
  if (raw === undefined) return key;
  if (!params) return raw;
  return raw.replace(/\{\{\s*(\w+)\s*\}\}/g, (_m, name) =>
    params[name] === undefined ? "" : String(params[name])
  );
}

/** Drop-in for react-i18next's hook so copied components need no edits. */
export function useTranslation() {
  return { t };
}
